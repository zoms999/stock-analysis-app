-- 2. Market Prices Table
CREATE TABLE public.market_prices (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ticker_symbol varchar(50) NOT NULL REFERENCES public.assets(symbol), -- Foreign key for integrity
    price numeric NOT NULL,
    recorded_at timestamptz DEFAULT now(),
    
    -- Ensure unique price per ticker per timestamp to avoid duplicates
    CONSTRAINT market_prices_unique_entry UNIQUE (ticker_symbol, recorded_at)
);

-- Index for fast lookup by ticker and time
CREATE INDEX idx_market_prices_search ON public.market_prices (ticker_symbol, recorded_at DESC);

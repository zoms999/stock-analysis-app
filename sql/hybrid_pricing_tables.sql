-- 1. Assets Table (Ticker Mapping)
CREATE TABLE public.assets (
    symbol varchar(50) PRIMARY KEY, -- Our internal ID (e.g., BTC-USD, TSLA)
    api_id varchar(100) NOT NULL,   -- External API ID (e.g., bitcoin, TSLA)
    asset_type varchar(20) NOT NULL, -- CRYPTO, STOCK
    is_active boolean DEFAULT true,   -- Switch to enable/disable collection
    created_at timestamptz DEFAULT now()
);

